export function getFeatureById(id: string): TourFeatureItem | undefined {
  return ALL_TOUR_FEATURES.find((f) => f.id === id);
}

export function getTrackById(trackId: string): TourTrack | undefined {
  return TOUR_TRACKS.find((t) => t.id === trackId);
}

export function buildTourStepsForTrack(trackId: string): TourStep[] {
  const track = getTrackById(trackId) ?? TOUR_TRACKS[0];
  const steps: TourStep[] = [];
  for (const id of track.stepIds) {
    const feat = getFeatureById(id);
    if (feat) {
      steps.push({
        id: feat.id,
        title: feat.title,
        category: feat.category,
        targetSelector: feat.targetSelector,
        route: feat.route,
        summary: feat.summary,
        description: feat.description,
        capabilities: feat.capabilities,
        proTips: feat.proTips,
        badge: feat.badge,
        position: "bottom",
      });
    }
  }
  return steps;
}

